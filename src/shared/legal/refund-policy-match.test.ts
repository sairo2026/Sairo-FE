import { describe, expect, it } from "vitest";
import { REFUND_BODY } from "./documents/refund";

// 토스페이먼츠 가맹 심사가 끝난 뒤 구현에 맞게 정정한 1절 문장이다.
// 정정 전 문장은 서비스 장애 환불을 일할 계산으로, 환불 신청을 결제 내역 화면의 일괄 신청으로 적었다.
const REFUND_POLICY_SUMMARY =
  "사이로는 월 선불 자동결제 구독 서비스입니다. 무료 체험 기간에는 결제가 발생하지 않습니다. 해지는 언제든 신청할 수 있고, 해지를 예약하면 이미 결제한 이용기간이 끝날 때까지 서비스를 이용할 수 있으며 다음 결제부터 청구되지 않습니다. 이 경우 이미 결제한 기간의 환불은 없습니다. 사무소를 지금 바로 종료하거나 사무소 인증이 중단된 경우에는 남은 이용기간을 일할 계산하여 환불합니다. 사이로의 서비스 장애로 이용하지 못한 경우에는 회사가 장애의 영향을 확인해 정한 금액을 환불하며 이미 결제한 금액을 넘지 않습니다. 사무소를 종료한 뒤 결제 승인 지연이나 시스템 오류로 승인된 금액은 운영자가 검토하여 전액 환불합니다. 결제 오류나 중복 결제는 전액 환불합니다. 중복 결제와 잘못 결제된 금액의 환불은 결제 내역 화면에서 신청하고, 사무소 종료와 인증 중단과 종료 뒤 승인된 결제의 환불은 시스템이 접수하며, 서비스 장애의 환불은 고객지원으로 문의해 주세요. 환불은 결제하신 수단으로 처리됩니다. 문의는 고객센터로 접수해 주세요.";

describe("환불정책 1절 요약", () => {
  it("환불정책 1절은 고정한 정정 문장과 한 글자도 다르지 않다", () => {
    const section = REFUND_BODY.split("#### 1. 환불정책 요약")[1]?.split("#### 2.")[0]?.trim();
    expect(section).toBe(REFUND_POLICY_SUMMARY);
  });

  it("1절은 서비스 장애를 일할 계산으로 적지 않고 회사가 정한 금액으로 적는다", () => {
    expect(REFUND_POLICY_SUMMARY).not.toContain("서비스 장애가 있는 경우에는 남은 이용기간을 일할");
    expect(REFUND_POLICY_SUMMARY).toContain("회사가 장애의 영향을 확인해 정한 금액");
  });
});
